STATE_CLASSES = {
    "neutral": "neutral-cell",
    "source": "source-cell",
    "copied": "copied-cell",
    "init": "init-cell",
    "unused": "unused-cell",
}


def grid_width(columns: int) -> float:
    return columns * CELL_SIZE + (columns - 1) * CELL_GAP


def grid_height(rows: int) -> float:
    return rows * CELL_SIZE + (rows - 1) * CELL_GAP


def data_center_x(card_x: float, side: str) -> float:
    """Bias data inward to reserve a mirrored outer annotation rail."""
    direction = 1 if side == "left" else -1
    return card_x + CARD_WIDTH / 2 + direction * DATA_CENTER_BIAS


def centered_grid_x(card_x: float, columns: int, side: str) -> float:
    """Center a parameter grid within its card's data region."""
    return data_center_x(card_x, side) - grid_width(columns) / 2


def annotation_positions(
    *,
    card_x: float,
    group_x: float,
    group_width: float,
    side: str,
) -> tuple[float, float]:
    """Return mirrored index and axis-title centers with safe card margins."""
    if side == "left":
        index_x = group_x - ROW_INDEX_GAP
        axis_x = max(
            index_x - AXIS_TO_INDEX_GAP,
            card_x + AXIS_CENTER_EDGE_INSET,
        )
    else:
        index_x = group_x + group_width + ROW_INDEX_GAP
        axis_x = min(
            index_x + AXIS_TO_INDEX_GAP,
            card_x + CARD_WIDTH - AXIS_CENTER_EDGE_INSET,
        )
    return index_x, axis_x


def add_parameter_slice(svg: Svg, *, x: float, y: float, state: str) -> None:
    """Draw one parameter slice using the shared geometry for every figure."""
    svg.rect(
        x,
        y,
        CELL_SIZE,
        CELL_SIZE,
        css_class=STATE_CLASSES[state],
        radius=CELL_RADIUS,
        extra=f' stroke-width="{CELL_STROKE_WIDTH}"',
    )


def add_badge(svg: Svg, x: float, y: float, label: str) -> None:
    svg.circle(
        x,
        y,
        11,
        css_class="mapping-badge",
        extra=' stroke-width="2"',
    )
    svg.text(x, y + 0.5, label, css_class="badge-text", anchor="middle")


def add_grid(
    svg: Svg,
    *,
    card_x: float,
    x: float,
    y: float,
    rows: int,
    columns: int,
    states: list[list[str]],
    badges: dict[tuple[int, int], str] | None = None,
    side: str,
) -> None:
    badges = badges or {}
    svg.text(
        x + grid_width(columns) / 2,
        y - TRACK_TITLE_OFFSET,
        "TRACK 't' →",
        css_class="axis-title",
        anchor="middle",
    )
    for column in range(columns):
        cx = x + column * CELL_PITCH + CELL_SIZE / 2
        svg.text(cx, y - COLUMN_INDEX_OFFSET, str(column), css_class="axis", anchor="middle")

    row_index_x, row_title_x = annotation_positions(
        card_x=card_x,
        group_x=x,
        group_width=grid_width(columns),
        side=side,
    )
    row_title_y = y + grid_height(rows) / 2
    svg.text(row_title_x, row_title_y - 10, "ORG 'o'", css_class="axis-title", anchor="middle")
    svg.text(row_title_x, row_title_y + 12, "↓", css_class="axis-title", anchor="middle")
    for row in range(rows):
        cy = y + row * CELL_PITCH + CELL_SIZE / 2
        svg.text(row_index_x, cy, str(row), css_class="axis", anchor="middle")
        for column in range(columns):
            cell_x = x + column * CELL_PITCH
            cell_y = y + row * CELL_PITCH
            add_parameter_slice(svg, x=cell_x, y=cell_y, state=states[row][column])
            badge = badges.get((row, column))
            if badge is not None:
                add_badge(
                    svg,
                    cell_x + CELL_SIZE / 2,
                    cell_y + CELL_SIZE / 2,
                    badge,
                )


def add_org_column(
    svg: Svg,
    *,
    card_x: float,
    x: float,
    y: float,
    states: list[str],
    side: str,
    badges: dict[int, str] | None = None,
) -> None:
    badges = badges or {}
    label_x, axis_x = annotation_positions(
        card_x=card_x,
        group_x=x,
        group_width=CELL_SIZE,
        side=side,
    )
    axis_y = y + grid_height(len(states)) / 2
    svg.text(axis_x, axis_y - 10, "ORG 'o'", css_class="axis-title", anchor="middle")
    svg.text(axis_x, axis_y + 12, "↓", css_class="axis-title", anchor="middle")
    for index, state in enumerate(states):
        cell_y = y + index * CELL_PITCH
        add_parameter_slice(svg, x=x, y=cell_y, state=state)
        svg.text(
            label_x,
            cell_y + CELL_SIZE / 2,
            str(index),
            css_class="index",
            anchor="middle",
        )
        badge = badges.get(index)
        if badge is not None:
            add_badge(
                svg,
                x + CELL_SIZE / 2,
                cell_y + CELL_SIZE / 2,
                badge,
            )


def org_center(y: float, index: int) -> float:
    return y + index * CELL_PITCH + CELL_SIZE / 2


def add_gate(
    svg: Svg,
    *,
    y: float,
    left: float = ORG_SOURCE_X + CELL_SIZE + 10,
    right: float = ORG_TARGET_X - 10,
) -> None:
    svg.line(
        left,
        y,
        CANVAS_CENTER_X - GATE_LINE_CLEARANCE,
        y,
        css_class="gate-line",
        width=2.5,
        extra=' stroke-dasharray="6 7"',
    )
    svg.line(
        CANVAS_CENTER_X + GATE_LINE_CLEARANCE,
        y,
        right,
        y,
        css_class="gate-line",
        width=2.5,
        extra=' stroke-dasharray="6 7"',
    )
    svg.circle(CANVAS_CENTER_X, y, 22, css_class="stop-ring", extra=' stroke-width="2.5"')
    svg.line(
        CANVAS_CENTER_X - 10,
        y - 10,
        CANVAS_CENTER_X + 10,
        y + 10,
        css_class="stop-line",
        width=3.5,
        extra=' stroke-linecap="round"',
    )
    svg.line(
        CANVAS_CENTER_X + 10,
        y - 10,
        CANVAS_CENTER_X - 10,
        y + 10,
        css_class="stop-line",
        width=3.5,
        extra=' stroke-linecap="round"',
    )


def add_standard_frame(svg: Svg) -> None:
    svg.rect(0, 0, STANDARD_WIDTH, STANDARD_HEIGHT, css_class="canvas", radius=22)
    for x, title in ((SOURCE_CARD_X, "CHECKPOINT"), (TARGET_CARD_X, "TARGET")):
        svg.rect(
            x + 5,
            CARD_Y + 7,
            CARD_WIDTH,
            CARD_HEIGHT,
            css_class="card-shadow",
            radius=18,
        )
        svg.rect(
            x,
            CARD_Y,
            CARD_WIDTH,
            CARD_HEIGHT,
            css_class="card",
            radius=18,
            extra=' stroke-width="1.5"',
        )
        svg.text(
            x + CARD_WIDTH / 2,
            CARD_TITLE_Y,
            title,
            css_class="card-title",
            anchor="middle",
        )
        svg.line(
            x + CARD_CONTENT_INSET,
            HEADER_SEPARATOR_Y,
            x + CARD_WIDTH - CARD_CONTENT_INSET,
            HEADER_SEPARATOR_Y,
            css_class="separator",
            width=1.5,
        )
        svg.line(
            x + CARD_CONTENT_INSET,
            SECTION_SEPARATOR_Y,
            x + CARD_WIDTH - CARD_CONTENT_INSET,
            SECTION_SEPARATOR_Y,
            css_class="separator",
            width=1.5,
        )
        svg.text(
            x + LANE_LABEL_INSET,
            ORGANISM_TITLE_Y,
            "ORGANISM SLICE 'o'",
            css_class="lane-label",
        )
        svg.text(
            x + LANE_LABEL_INSET,
            HEAD_TITLE_Y,
            "HEAD SLICE (o, t)",
            css_class="lane-label",
        )


def make_legend_diagram() -> str:
    svg = Svg(
        width=LEGEND_WIDTH,
        height=LEGEND_HEIGHT,
        title="Checkpoint loading figure legend",
        description=(
            "Every flat square is one parameter slice, drawn schematically as shape C. "
            "The introductory square is neutral gray to not indicate any model. "
            "Pale blue with a blue border is a checkpoint slice. Pale orange with an "
            "orange border is an untouched target slice. A copied target combines a "
            "checkpoint-blue fill with a target-orange border. A faded checkpoint "
            "slice with a dashed blue border is unused."
        ),
    )
    svg.rect(0, 0, LEGEND_WIDTH, LEGEND_HEIGHT, css_class="canvas", radius=18)

    add_parameter_slice(svg, x=62, y=22, state="neutral")
    svg.text(80, 40, "[C]", css_class="cell-text", anchor="middle")
    svg.text(120, 30, "ONE SQUARE = ONE PARAMETER SLICE", css_class="legend-title")
    svg.text(
        120,
        53,
        "all values move together (gray indicates no specific model)",
        css_class="legend-note",
    )

    legend_items = (
        (105, "source", "CHECKPOINT"),
        (330, "init", "TARGET"),
        (550, "unused", "UNUSED"),
        (770, "copied", "COPIED"),
    )
    for x, state, label in legend_items:
        add_parameter_slice(svg, x=x, y=91, state=state)
        svg.text(x + CELL_SIZE + 10, 109, label, css_class="legend")
    return svg.render()


def add_prefix_arrow(svg: Svg, *, x1: float, x2: float, y: float) -> None:
    svg.text((x1 + x2) / 2, y - 18, "PREFIX", css_class="prefix-label", anchor="middle")
    svg.path(
        f"M {x1} {y} L {x2} {y}",
        css_class="copy-line",
        width=3,
        marker="arrow-copy",
    )


def overlap_center(y: float, source_count: int, target_count: int) -> float:
    """Return the center of the shared, top-aligned prefix."""
    return y + grid_height(min(source_count, target_count)) / 2


def make_prefix_case_diagram(
    *,
    title: str,
    description: str,
    source_org: list[str],
    target_org: list[str],
    source_grid: list[list[str]],
    target_grid: list[list[str]],
) -> str:
    svg = Svg(
        width=STANDARD_WIDTH,
        height=STANDARD_HEIGHT,
        title=title,
        description=description,
    )
    add_standard_frame(svg)

    add_org_column(
        svg,
        card_x=SOURCE_CARD_X,
        x=ORG_SOURCE_X,
        y=ORG_Y,
        states=source_org,
        side="left",
    )
    add_org_column(
        svg,
        card_x=TARGET_CARD_X,
        x=ORG_TARGET_X,
        y=ORG_Y,
        states=target_org,
        side="right",
    )
    add_prefix_arrow(
        svg,
        x1=ORG_SOURCE_X + CELL_SIZE + 16,
        x2=ORG_TARGET_X - 16,
        y=overlap_center(ORG_Y, len(source_org), len(target_org)),
    )

    source_columns = len(source_grid[0])
    target_columns = len(target_grid[0])
    source_x = centered_grid_x(SOURCE_CARD_X, source_columns, "left")
    target_x = centered_grid_x(TARGET_CARD_X, target_columns, "right")
    add_grid(
        svg,
        card_x=SOURCE_CARD_X,
        x=source_x,
        y=GRID_Y,
        rows=len(source_grid),
        columns=source_columns,
        states=source_grid,
        side="left",
    )
    add_grid(
        svg,
        card_x=TARGET_CARD_X,
        x=target_x,
        y=GRID_Y,
        rows=len(target_grid),
        columns=target_columns,
        states=target_grid,
        side="right",
    )
    add_prefix_arrow(
        svg,
        x1=source_x + grid_width(source_columns) + 16,
        x2=target_x - 16,
        y=overlap_center(GRID_Y, len(source_grid), len(target_grid)),
    )
    return svg.render()


def make_prefix_loading_diagram() -> str:
    copied_organisms = min(EXAMPLE_CHECKPOINT_ORGANISMS, EXAMPLE_TARGET_ORGANISMS)
    copied_tracks = min(EXAMPLE_CHECKPOINT_TRACKS, EXAMPLE_TARGET_TRACKS)
    return make_prefix_case_diagram(
        title="Prefix loading with independently sized axes",
        description=(
            "The checkpoint has fewer organisms but more prediction-track/output "
            "indices than the target. The overlapping organism-by-output prefix "
            "copies. The additional target organism stays initialized, and the "
            "additional checkpoint output is unused."
        ),
        source_org=["source"] * EXAMPLE_CHECKPOINT_ORGANISMS,
        target_org=["copied"] * copied_organisms
        + ["init"] * (EXAMPLE_TARGET_ORGANISMS - copied_organisms),
        source_grid=[
            ["source"] * copied_tracks
            + ["unused"] * (EXAMPLE_CHECKPOINT_TRACKS - copied_tracks)
            for _ in range(EXAMPLE_CHECKPOINT_ORGANISMS)
        ],
        target_grid=[["copied"] * EXAMPLE_TARGET_TRACKS for _ in range(copied_organisms)]
        + [
            ["init"] * EXAMPLE_TARGET_TRACKS
            for _ in range(EXAMPLE_TARGET_ORGANISMS - copied_organisms)
        ],
    )


