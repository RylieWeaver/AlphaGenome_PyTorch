def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit unsuccessfully if committed diagrams differ from generated output",
    )
    args = parser.parse_args()

    outputs = generated_outputs()
    if args.check:
        stale = [
            name
            for name, content in outputs.items()
            if not (OUTPUT_DIR / name).is_file()
            or (OUTPUT_DIR / name).read_text(encoding="utf-8") != content
        ]
        if stale:
            print("Stale checkpoint diagrams: " + ", ".join(stale))
            return 1
        print("Checkpoint diagrams are up to date.")
        return 0

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        path = OUTPUT_DIR / name
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(DOCS_DIR.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
