class Svg:
    """Tiny SVG builder with only the primitives these diagrams need."""

    def __init__(
        self,
        *,
        width: int,
        height: int,
        title: str,
        description: str,
    ) -> None:
        self.width = width
        self.height = height
        self.title = title
        self.description = description
        self.elements: list[str] = []

    def raw(self, value: str) -> None:
        self.elements.append(value)

    def rect(
        self,
        x: float,
        y: float,
        width: float,
        height: float,
        *,
        css_class: str = "",
        radius: float = 0,
        extra: str = "",
    ) -> None:
        class_attr = f' class="{css_class}"' if css_class else ""
        radius_attr = f' rx="{radius}" ry="{radius}"' if radius else ""
        self.raw(
            f'<rect x="{x}" y="{y}" width="{width}" height="{height}"'
            f'{radius_attr}{class_attr}{extra}/>'
        )

    def line(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        *,
        css_class: str,
        width: float = 2,
        extra: str = "",
    ) -> None:
        self.raw(
            f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" '
            f'class="{css_class}" stroke-width="{width}"{extra}/>'
        )

    def path(
        self,
        d: str,
        *,
        css_class: str,
        width: float = 3,
        marker: str | None = None,
        extra: str = "",
    ) -> None:
        marker_attr = f' marker-end="url(#{marker})"' if marker else ""
        self.raw(
            f'<path d="{d}" class="{css_class}" fill="none" '
            f'stroke-width="{width}" stroke-linecap="round" '
            f'stroke-linejoin="round"{marker_attr}{extra}/>'
        )

    def circle(
        self,
        cx: float,
        cy: float,
        radius: float,
        *,
        css_class: str,
        extra: str = "",
    ) -> None:
        self.raw(
            f'<circle cx="{cx}" cy="{cy}" r="{radius}" '
            f'class="{css_class}"{extra}/>'
        )

    def text(
        self,
        x: float,
        y: float,
        value: str,
        *,
        css_class: str = "ink",
        anchor: str = "start",
        extra: str = "",
    ) -> None:
        self.raw(
            f'<text x="{x}" y="{y}" class="{css_class}" '
            f'text-anchor="{anchor}" dominant-baseline="middle"{extra}>'
            f'{escape(value)}</text>'
        )

    def render(self) -> str:
        body = "\n  ".join(self.elements)
        return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by docs/_scripts/generate_checkpoint_loading_diagrams.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.width} {self.height}"
     role="img" aria-labelledby="svg-title svg-description">
  <title id="svg-title">{escape(self.title)}</title>
  <desc id="svg-description">{escape(self.description)}</desc>
  {DEFS}
  {body}
</svg>
'''


