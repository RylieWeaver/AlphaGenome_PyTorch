def add_mapping_index(
    svg: Svg,
    *,
    x: float,
    y: float,
    value: str,
    role: str,
) -> None:
    svg.text(
        x,
        y + 0.5,
        value,
        css_class=f"mapping-index-text mapping-{role}-text",
        anchor="middle",
    )


def add_mapping_contents(
    svg: Svg,
    *,
    x: float,
    y: float,
    label: str,
    source: str,
    target: str,
) -> None:
    add_badge(svg, x + 17, y, label)
    add_mapping_index(svg, x=x + 53, y=y, value=source, role="source")
    svg.text(x + 82, y + 0.5, "→", css_class="mapping-arrow", anchor="middle")
    add_mapping_index(svg, x=x + 112, y=y, value=target, role="target")


def add_mapping_row(
    svg: Svg,
    *,
    y: float,
    label: str,
    source: str,
    target: str,
) -> None:
    svg.rect(
        MAPPING_CHIP_X,
        y - MAPPING_CHIP_HEIGHT / 2,
        MAPPING_CHIP_WIDTH,
        MAPPING_CHIP_HEIGHT,
        css_class="mapping-chip",
        radius=MAPPING_CHIP_HEIGHT / 2,
        extra=' stroke-width="1.75"',
    )
    add_mapping_contents(
        svg,
        x=MAPPING_CHIP_X,
        y=y,
        label=label,
        source=source,
        target=target,
    )


def add_mapping_chip(
    svg: Svg,
    *,
    y: float,
    label: str,
    source: tuple[int, int],
    target: tuple[int, int],
) -> None:
    add_mapping_row(
        svg,
        y=y,
        label=label,
        source=f"({source[0]},{source[1]})",
        target=f"({target[0]},{target[1]})",
    )


def add_organism_mapping_chip(
    svg: Svg,
    *,
    y: float,
    label: str,
    source: int,
    target: int,
) -> None:
    add_mapping_row(
        svg,
        y=y,
        label=label,
        source=str(source),
        target=str(target),
    )


